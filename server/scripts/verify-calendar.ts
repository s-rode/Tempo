import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import mongoose from 'mongoose';
import jwt from 'jsonwebtoken';
import { ActiveWindowEventModel } from '../src/models/activeWindowEvent';
import { FocusRuntimeModel } from '../src/models/focusRuntime';
import { createCustomRun, freezePhase, resumePhase, resumeAfterSystemCapture, saveRuntime } from '../src/services/focusRuntime';
import { setCalendarPause } from '../src/services/calendarPause';
import { calculatePeriodAnalytics } from '../src/services/analytics';
import { armFocusRuntimeDeadline } from '../src/services/focusRuntimeScheduler';
import { activeWindowEventsRouter } from '../src/routers/activeWindowEvents';

const database = `tempo_test_calendar_${randomUUID().replaceAll('-', '')}`;
const userId = new mongoose.Types.ObjectId().toString();
process.env.AUTH_SECRET = randomUUID();
try {
  await mongoose.connect(`mongodb://127.0.0.1:27017/${database}`);
  await ActiveWindowEventModel.init();
  const now = Date.now();
  const start = now - 5 * 60_000;
  const runtime = new FocusRuntimeModel({userId, run: createCustomRun('Test calendar accounting', 60, start)});
  freezePhase(runtime, now);
  runtime.manualPauseUntilMs = now + 60 * 60_000;
  runtime.manualPausedAtMs = now;
  await runtime.save();
  await ActiveWindowEventModel.create({userId, ownerName: 'Test editor', type: 'window', timestamp: start, categoryId: 'work'});
  await setCalendarPause(userId, {untilMs: now + 800, timestamp: now, eventIds: ['test-occurrence']});
  const paused = await FocusRuntimeModel.findOne({userId});
  assert.equal(paused?.calendarPauseUntilMs, now + 800);
  assert.equal(paused?.manualPauseUntilMs, now + 60 * 60_000);
  assert.equal(paused?.run?.phases[0].activeElapsedMs, 5 * 60_000);
  const caller = activeWindowEventsRouter.createCaller({});
  const response = await caller.create({token: jwt.sign({userId}, process.env.AUTH_SECRET), ownerName: 'Late foreground capture', type: 'window', timestamp: now + 10, title: 'Must not be saved during the event'});
  assert.equal(response.ownerName, 'Calendar Pause');
  assert.equal(await ActiveWindowEventModel.countDocuments({ownerName: 'Late foreground capture'}), 0);
  const events = await ActiveWindowEventModel.find({userId}).lean();
  const totals = calculatePeriodAnalytics(events as any, [{_id: 'work', name: 'Work', isProductive: true}] as any, start, now + 60_000, now + 60_000).totals;
  assert.equal(totals.focusedMs, 5 * 60_000);
  assert.equal(totals.uncertainMs, 0);
  await Bun.sleep(1400);
  const ended = await FocusRuntimeModel.findOne({userId});
  assert.equal(ended?.calendarPauseUntilMs, null);
  assert.equal(ended?.manualPauseUntilMs, now + 60 * 60_000);
  assert.equal(ended?.run?.phases[0].runningSinceMs, null);
  assert.equal(ended?.run?.phases[0].activeElapsedMs, 5 * 60_000);
  ended!.manualPauseUntilMs = null;
  ended!.manualPausedAtMs = null;
  ended!.awaitingSystemResumeCapture = false;
  resumePhase(ended, Date.now());
  await saveRuntime(ended, {rearmScheduler: false});
  const second = Date.now();
  await setCalendarPause(userId, {untilMs: second + 600, timestamp: second, eventIds: ['second-occurrence']});
  await Bun.sleep(1100);
  const awaiting = await FocusRuntimeModel.findOne({userId});
  assert.equal(awaiting?.calendarPauseUntilMs, null);
  assert.equal(awaiting?.awaitingSystemResumeCapture, true);
  assert.equal(awaiting?.run?.phases[0].runningSinceMs, null);
  const fresh = await resumeAfterSystemCapture(userId);
  assert.equal(fresh.trackingState, 'active');
  assert.equal(fresh.suspension.reasons.length, 0);
  console.log('PASS: real database pause boundaries, rejected late captures, excluded event duration, automatic event expiry, and independent manual pause.');
} finally {
  await FocusRuntimeModel.deleteMany({userId});
  await armFocusRuntimeDeadline(userId);
  if (mongoose.connection.name === database && database.startsWith('tempo_test_calendar_')) await mongoose.connection.dropDatabase();
  await mongoose.disconnect();
}
